using System.Security.Cryptography;
using System.Text;
using Chatbot.Application.Abstractions;
using Chatbot.Application.Options;
using Chatbot.Domain;
using Chatbot.Infrastructure.Chat;

namespace Chatbot.Infrastructure.Seed;

/// <summary>
/// Writes api/db/local/seed.sql: the five synthetic test participants of the client mock, with only the code HASHES
/// (never the plain codes, never the pepper). It does NOT connect to any database; the file is run by hand.
/// Ids are derived from stable names, so running the script again changes nothing (ON CONFLICT DO NOTHING).
/// </summary>
public sealed class SeedSqlGenerator(ISecretHasher hasher, DocumentsOptions documents, TimeProvider clock)
{
    private const string OldVersion = "0.0-eski";

    private sealed record SeedParticipant(string Label, string Code, ParticipantStatus Status);

    private static readonly SeedParticipant[] Participants =
    [
        new("seed-1", "ABCD2345", ParticipantStatus.Invited), // new: nothing done yet
        new("seed-2", "BCDF3456", ParticipantStatus.Active),  // everything done + nickname + 2 finished conversations
        new("seed-3", "CDFG4567", ParticipantStatus.Active),  // consent withdrawn
        new("seed-4", "DFGH5678", ParticipantStatus.Revoked), // revoked code
        new("seed-5", "FGHJ6789", ParticipantStatus.Active),  // old notice and consent versions
    ];

    public string Generate()
    {
        var now = clock.GetUtcNow();
        var sql = new StringBuilder();
        sql.AppendLine("-- =====================================================================================");
        sql.AppendLine("-- seed.sql : synthetic test participants (GENERATED by `generate-seed`, do not commit)");
        sql.AppendLine("-- =====================================================================================");
        sql.AppendLine("-- SYNTHETIC DATA ONLY. Real patient data never goes into this database.");
        sql.AppendLine("-- Contains only code HASHES (no plain codes, no pepper). Idempotent: ON CONFLICT DO NOTHING.");
        sql.AppendLine("-- Run it after 001_initial.sql and verify.sql. If Auth:CodePepper changes later, delete the");
        sql.AppendLine("-- 'seed-%' participants first (their hashes would no longer match), then generate and run again.");
        sql.AppendLine("-- =====================================================================================");
        sql.AppendLine();
        sql.AppendLine("BEGIN;");
        sql.AppendLine();

        var participantRows = new List<string>();
        var consentRows = new List<string>();
        var conversationRows = new List<string>();
        var messageRows = new List<string>();

        foreach (var p in Participants)
        {
            var id = StableId($"participant:{p.Label}");
            var nickname = p.Label is "seed-2" or "seed-3" or "seed-5" ? "Deneme" : null;
            participantRows.Add($"({Uuid(id)}, {Lit(hasher.HashCode(p.Code))}, {Lit(p.Label)}, {Lit(p.Status.ToString())}, {Lit(nickname)}, {Ts(now.AddDays(-7))}, {Ts(p.Status == ParticipantStatus.Invited ? null : now.AddDays(-1))})");

            void Consent(string key, ConsentType type, string version, bool granted, int daysAgo) =>
                consentRows.Add($"({Uuid(StableId($"consent:{p.Label}:{key}"))}, {Uuid(id)}, {Lit(type.ToString())}, {Lit(version)}, {(granted ? "TRUE" : "FALSE")}, {Ts(now.AddDays(-daysAgo))})");

            switch (p.Label)
            {
                case "seed-2":
                    Consent("notice", ConsentType.PrivacyNotice, documents.PrivacyNoticeVersion, true, 6);
                    Consent("consent", ConsentType.ExplicitConsent, documents.ConsentVersion, true, 6);
                    break;
                case "seed-3":
                    Consent("notice", ConsentType.PrivacyNotice, documents.PrivacyNoticeVersion, true, 6);
                    Consent("consent", ConsentType.ExplicitConsent, documents.ConsentVersion, true, 6);
                    Consent("withdrawn", ConsentType.ExplicitConsent, documents.ConsentVersion, false, 3);
                    break;
                case "seed-5":
                    Consent("notice", ConsentType.PrivacyNotice, OldVersion, true, 6);
                    Consent("consent", ConsentType.ExplicitConsent, OldVersion, true, 6);
                    break;
            }

            if (p.Label == "seed-2")
            {
                // The same two finished conversations as the client mock, with the same canned replies.
                AddFinishedConversation(id, "a", daysAgo: 2, now, conversationRows, messageRows,
                [
                    ("Bugün kendimi çok yorgun hissediyorum, aklım hep dağınık.", FakeReplies.Pick("yorgun", 0).Text),
                    ("Biraz sakinleşmek istiyorum.", FakeReplies.Pick("sakinleşmek", 0).Text),
                ]);
                AddFinishedConversation(id, "b", daysAgo: 5, now, conversationRows, messageRows,
                [
                    ("Ailemle konuşmak bana zor geliyor, kimse anlamıyor gibi.", FakeReplies.Pick("aile", 0).Text),
                    ("Endişelerim gece daha da büyüyor.", FakeReplies.Pick("endişe", 0).Text),
                    ("Teşekkür ederim, biraz rahatladım.", FakeReplies.Pick("teşekkür ederim, biraz rahatladım", 1).Text),
                ]);
            }
        }

        Insert(sql, "participants", "id, code_hash, label, status, nickname, created_at, last_seen_at", participantRows);
        Insert(sql, "consent_records", "id, participant_id, type, document_version, granted, \"timestamp\"", consentRows);
        Insert(sql, "conversations", "id, participant_id, started_at, ended_at, peplau_phase", conversationRows);
        Insert(sql, "messages", "id, conversation_id, role, content, created_at, is_crisis, client_message_id, completion", messageRows);

        sql.AppendLine("COMMIT;");
        return sql.ToString();
    }

    private void AddFinishedConversation(
        Guid participantId,
        string key,
        int daysAgo,
        DateTimeOffset now,
        List<string> conversations,
        List<string> messages,
        (string User, string Assistant)[] turns)
    {
        var conversationId = StableId($"conversation:{participantId}:{key}");
        var start = now.AddDays(-daysAgo);
        conversations.Add($"({Uuid(conversationId)}, {Uuid(participantId)}, {Ts(start)}, {Ts(start.AddMinutes((turns.Length * 3) + 2))}, 'Orientation')");

        for (var i = 0; i < turns.Length; i++)
        {
            messages.Add($"({Uuid(StableId($"message:{conversationId}:{i}:u"))}, {Uuid(conversationId)}, 'User', {Lit(turns[i].User)}, {Ts(start.AddMinutes(i * 3))}, FALSE, {Uuid(StableId($"client:{conversationId}:{i}"))}, NULL)");
            messages.Add($"({Uuid(StableId($"message:{conversationId}:{i}:a"))}, {Uuid(conversationId)}, 'Assistant', {Lit(turns[i].Assistant)}, {Ts(start.AddMinutes((i * 3) + 1))}, FALSE, NULL, 'Complete')");
        }
    }

    private static void Insert(StringBuilder sql, string table, string columns, List<string> rows)
    {
        if (rows.Count == 0)
        {
            return;
        }

        sql.AppendLine($"INSERT INTO public.{table} ({columns}) VALUES");
        sql.AppendLine(string.Join(",\n", rows.Select(r => "    " + r)));
        sql.AppendLine("ON CONFLICT DO NOTHING;");
        sql.AppendLine();
    }

    private static Guid StableId(string name) =>
        new(SHA256.HashData(Encoding.UTF8.GetBytes("lumind-seed:" + name))[..16]);

    private static string Uuid(Guid id) => $"'{id}'";

    private static string Ts(DateTimeOffset? value) =>
        value is null ? "NULL" : $"'{value.Value.UtcDateTime:yyyy-MM-dd HH:mm:ss}+00'";

    private static string Lit(string? value) =>
        value is null ? "NULL" : "'" + value.Replace("'", "''", StringComparison.Ordinal) + "'";
}
